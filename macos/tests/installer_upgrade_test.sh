#!/usr/bin/env bash
set -euo pipefail

installer=${1:?Usage: bash installer_upgrade_test.sh INSTALLER_TEMPLATE}
workspace=$(mktemp -d "${TMPDIR:-/tmp}/beankey-installer-upgrade.XXXXXX")
# Leave fixtures and installer output available for diagnosis; Nix owns TMPDIR.

fail() {
  printf '%s: %s\nTest workspace: %s\n' "$kind" "$1" "$workspace" >&2
  printf '\nInstaller stdout:\n' >&2
  cat "$stdout" >&2
  printf '\nInstaller stderr:\n' >&2
  cat "$stderr" >&2
  exit 1
}

for kind in standalone home-manager; do
  home="$workspace/$kind"
  support="$home/Library/Application Support/beanKey"
  expected="$workspace/$kind-config.toml"
  stdout="$workspace/$kind.stdout"
  stderr="$workspace/$kind.stderr"
  mkdir -p "$support"
  cat > "$expected" <<EOF
# Generated by beanKey standalone installer
dictionary = "/existing/dictionary"
llama_backend_directory = "$support/package/share/beankey/llama-backend"
[learning]
mode = "nothing"
EOF
  if [[ "$kind" == home-manager ]]; then
    managed_config="$workspace/$kind-managed-config.toml"
    cp "$expected" "$managed_config"
    ln -s "$managed_config" "$support/config.toml"
  else
    cp "$expected" "$support/config.toml"
  fi

  if HOME="$home" bash "$installer" >"$stdout" 2>"$stderr"; then
    fail 'installer accepted an obsolete backend setting'
  fi
  grep -qF 'llama_backend_directory' "$stderr" || fail 'missing obsolete-setting diagnostic'
  grep -qF 'Home Manager' "$stderr" || fail 'missing Home Manager migration diagnostic'
  grep -qF 'config.toml' "$stderr" || fail 'missing configuration-path diagnostic'
  if [[ "$kind" == home-manager ]]; then
    [[ -L "$support/config.toml" ]] || fail 'configuration symlink was replaced'
    [[ "$(readlink "$support/config.toml")" == "$managed_config" ]] || fail 'configuration symlink target changed'
    cmp "$expected" "$managed_config" || fail 'managed configuration was modified'
  else
    [[ -f "$support/config.toml" && ! -L "$support/config.toml" ]] || fail 'configuration is no longer a regular file'
  fi
  cmp "$expected" "$support/config.toml" || fail 'configuration was modified'
  [[ ! -e "$support/package" && ! -L "$support/package" ]] || fail 'installer created a package root'
  [[ ! -e "$home/Library/Input Methods" && ! -L "$home/Library/Input Methods" ]] || fail 'installer created an Input Methods directory'
  printf '%s: obsolete configuration rejected without changes\n' "$kind"
done
